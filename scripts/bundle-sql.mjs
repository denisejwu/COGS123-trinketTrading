/**
 * Combines every migration + seed.sql into ONE file you can paste into the
 * Supabase SQL Editor in a single go:
 *
 *   npm run db:bundle   ->  supabase/setup-all.sql
 *
 * It's wrapped in a transaction (begin ... commit), so if anything fails,
 * nothing is saved and you can simply fix the problem and run it again.
 * Use it on a fresh project. For later changes, run only the new
 * migration file.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const migrationsDir = join(root, "supabase", "migrations");
const files = readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort();

const parts = [
  "-- PopSwap: complete database setup (all migrations + seed data).",
  "-- Generated by `npm run db:bundle`. Paste ALL of this into the Supabase",
  "-- SQL Editor and click Run. If anything fails, nothing is saved.",
  "",
  "begin;",
  "",
  ...files.map((f) => `-- >>>>> ${f}\n${readFileSync(join(migrationsDir, f), "utf8")}`),
  `-- >>>>> seed.sql\n${readFileSync(join(root, "supabase", "seed.sql"), "utf8")}`,
  "commit;",
  "",
];

const out = join(root, "supabase", "setup-all.sql");
writeFileSync(out, parts.join("\n"));
console.log(`Wrote ${out} (${files.length} migrations + seed)`);
