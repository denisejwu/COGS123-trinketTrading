/**
 * Combines migrations + seed.sql into ONE file you can paste into the
 * Supabase SQL Editor in a single go.
 *
 *   npm run db:bundle                  -> supabase/setup-all.sql (everything, for a new project)
 *   npm run db:bundle -- --from=0004   -> supabase/update.sql   (only 0004 and later, + seed)
 *
 * The file is wrapped in a transaction (begin ... commit), so if anything
 * fails, nothing is saved and you can fix the problem and run it again.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const from = process.argv.find((a) => a.startsWith("--from="))?.split("=")[1];
const migrationsDir = join(root, "supabase", "migrations");
const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .filter((f) => !from || f >= from);

const parts = [
  `-- PopSwap database ${from ? `update (migrations ${from} and later)` : "setup (all migrations)"} + seed data.`,
  "-- Generated by `npm run db:bundle`. Paste ALL of this into the Supabase",
  "-- SQL Editor and click Run. If anything fails, nothing is saved.",
  "",
  "begin;",
  "",
  ...files.map((f) => `-- >>>>> ${f}\n${readFileSync(join(migrationsDir, f), "utf8")}`),
  `-- >>>>> seed.sql\n${readFileSync(join(root, "supabase", "seed.sql"), "utf8")}`,
  "commit;",
  "",
];

const out = join(root, "supabase", from ? "update.sql" : "setup-all.sql");
writeFileSync(out, parts.join("\n"));
console.log(`Wrote ${out} (${files.join(", ")} + seed)`);
